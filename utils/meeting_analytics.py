import json
from typing import Dict, Any, List, Optional

def calculate_meeting_cost_roi(
    duration_seconds: float,
    speaker_count: int,
    action_items_count: int,
    decisions_count: int,
    avg_hourly_rate: float = 75.0,
    blocked_count: int = 0
) -> Dict[str, Any]:
    """
    Computes enterprise financial meeting cost, decision velocity, action-item
    followthrough density, and efficiency grade for enterprise ROI telemetry.
    """
    duration_hours = max(duration_seconds / 3600.0, 0.083)  # min 5 min
    duration_minutes = duration_seconds / 60.0
    effective_participants = max(speaker_count, 2)
    
    # Financial cost computation
    total_cost = duration_hours * effective_participants * avg_hourly_rate
    cost_per_minute = total_cost / max(duration_minutes, 1)
    
    # Decision velocity & action density
    decisions_per_hour = decisions_count / duration_hours
    actions_per_hour = action_items_count / duration_hours
    
    # Efficiency score: 0 to 100
    # Balanced weighting: outcomes produced vs duration spent
    base_score = min(actions_per_hour * 12 + decisions_per_hour * 20, 95)
    penalty = (blocked_count / max(action_items_count, 1)) * 25
    final_score = max(int(base_score - penalty), 10)
    
    if final_score >= 85:
        grade = "A (Highly Productive)"
        grade_color = "#169B69"
        recommendation = "Excellent outcome velocity. Maintain this sprint alignment structure."
    elif final_score >= 70:
        grade = "B (Constructive)"
        grade_color = "#2563EB"
        recommendation = "Solid outcome delivery. Consider shortening sync by 10 minutes to reduce cost."
    elif final_score >= 50:
        grade = "C (Moderate Efficiency)"
        grade_color = "#D98A16"
        recommendation = "Outcomes are low relative to duration. Require pre-meeting agendas to tighten sync."
    else:
        grade = "D (High Overhead / Review Required)"
        grade_color = "#DC4C64"
        recommendation = "High financial overhead with few concrete decisions. Consider replacing with asynchronous memos."

    return {
        "duration_minutes": round(duration_minutes, 1),
        "participants": effective_participants,
        "avg_hourly_rate": avg_hourly_rate,
        "estimated_total_cost_usd": round(total_cost, 2),
        "cost_per_minute_usd": round(cost_per_minute, 2),
        "cost_per_participant_usd": round(total_cost / effective_participants, 2),
        "decisions_per_hour": round(decisions_per_hour, 2),
        "actions_per_hour": round(actions_per_hour, 2),
        "efficiency_score": final_score,
        "efficiency_grade": grade,
        "grade_color": grade_color,
        "recommendation": recommendation,
    }

def format_slack_executive_brief(
    meeting_title: str,
    date_str: str,
    executive_summary: str,
    decisions: List[Dict[str, Any]],
    action_items: List[Dict[str, Any]],
    cost_roi: Optional[Dict[str, Any]] = None
) -> Dict[str, Any]:
    """
    Builds a ready-to-dispatch Slack Block Kit message structure for 1-click
    webhook integration or executive briefing broadcast.
    """
    blocks = [
        {
            "type": "header",
            "text": {
                "type": "plain_text",
                "text": f"📋 Executive Debrief: {meeting_title}",
                "emoji": True
            }
        },
        {
            "type": "context",
            "elements": [
                {
                    "type": "mrkdwn",
                    "text": f"🗓 *Date:* {date_str}  |  🤖 *Generated by MeetIntel AI*"
                }
            ]
        },
        {"type": "divider"},
        {
            "type": "section",
            "text": {
                "type": "mrkdwn",
                "text": f"*Executive Summary:*\n{executive_summary or 'No summary provided.'}"
            }
        }
    ]

    if cost_roi:
        blocks.append({
            "type": "section",
            "fields": [
                {"type": "mrkdwn", "text": f"*⏱ Duration:* {cost_roi['duration_minutes']} mins"},
                {"type": "mrkdwn", "text": f"*👥 Attendees:* {cost_roi['participants']}"},
                {"type": "mrkdwn", "text": f"*💰 Estimated Cost:* ${cost_roi['estimated_total_cost_usd']}"},
                {"type": "mrkdwn", "text": f"*⚡ Efficiency Grade:* {cost_roi['efficiency_grade']}"}
            ]
        })

    if decisions:
        dec_text = "\n".join([f"• *#{d.get('id', i+1)} {d.get('title', d.get('decision', ''))}*: {d.get('rationale', '')[:100]}" for i, d in enumerate(decisions[:4])])
        blocks.extend([
            {"type": "divider"},
            {
                "type": "section",
                "text": {
                    "type": "mrkdwn",
                    "text": f"*⚖️ Key Decisions Confirmed:*\n{dec_text}"
                }
            }
        ])

    if action_items:
        act_text = "\n".join([f"• *{a.get('task', '')}* → `{a.get('assigned_to', 'Unassigned')}` (Due: {a.get('deadline', 'N/A')})" for a in action_items[:5]])
        blocks.extend([
            {"type": "divider"},
            {
                "type": "section",
                "text": {
                    "type": "mrkdwn",
                    "text": f"*✅ Action Deliverables & Commitments:*\n{act_text}"
                }
            }
        ])

    blocks.append({
        "type": "context",
        "elements": [
            {
                "type": "mrkdwn",
                "text": "🔒 *Grounded with Verbatim Transcript Citations* • MeetIntel Enterprise Governance"
            }
        ]
    })

    return {
        "text": f"Executive Debrief: {meeting_title}",
        "blocks": blocks
    }

def format_markdown_executive_memo(
    meeting_title: str,
    date_str: str,
    executive_summary: str,
    decisions: List[Dict[str, Any]],
    action_items: List[Dict[str, Any]],
    cost_roi: Optional[Dict[str, Any]] = None
) -> str:
    """
    Renders an executive markdown memorandum suitable for pasting into email,
    Microsoft Teams, Confluence, or GitHub issue description.
    """
    lines = [
        f"# 📋 Executive Meeting Briefing: {meeting_title}",
        f"**Date:** {date_str} | **Platform:** MeetIntel AI Enterprise Engine\n",
        "## 1. Executive Summary",
        executive_summary or "Dialogue processed and verified against organizational memory.\n"
    ]

    if cost_roi:
        lines.extend([
            "## 2. Meeting Efficiency & Financial Cost Telemetry",
            f"- **Meeting Duration:** {cost_roi['duration_minutes']} minutes",
            f"- **Estimated Session Cost:** ${cost_roi['estimated_total_cost_usd']} USD (based on ${cost_roi['avg_hourly_rate']}/hr avg)",
            f"- **Decision Velocity:** {cost_roi['decisions_per_hour']} decisions/hr",
            f"- **Efficiency Rating:** {cost_roi['efficiency_grade']}",
            f"- **Optimization Insight:** {cost_roi['recommendation']}\n"
        ])

    if decisions:
        lines.append("## 3. Confirmed Decision Register")
        for i, d in enumerate(decisions, 1):
            title = d.get("title") or d.get("decision", "Agreed outcome")
            rationale = d.get("rationale") or d.get("context", "")
            lines.append(f"### {i}. {title}")
            if rationale:
                lines.append(f"- **Consensus Rationale:** {rationale}")
            if d.get("alternatives"):
                lines.append(f"- **Evaluated Alternatives:** {d['alternatives']}")
        lines.append("")

    if action_items:
        lines.append("## 4. Execution Commitments & Assigned Deliverables")
        lines.append("| Deliverable | Owner | Deadline | Priority | Status |")
        lines.append("| :--- | :--- | :--- | :--- | :--- |")
        for a in action_items:
            task = a.get("task", "")
            owner = a.get("assigned_to", "Needs assignment")
            deadline = a.get("deadline", "TBD")
            priority = a.get("priority", "Medium")
            status = a.get("status", "Pending")
            lines.append(f"| {task} | **{owner}** | {deadline} | {priority} | `{status}` |")
        lines.append("")

    lines.append("---\n*Generated automatically by MeetIntel AI with immutable audit verification.*")
    return "\n".join(lines)
